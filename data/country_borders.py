"""Builds the coarse European country borders bundled with the app (#15).

Input: Natural Earth 1:10m "Admin 0 - Countries" (public domain, https://www.naturalearthdata.com/,
version 5.1.2), GeoJSON from
https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_10m_admin_0_countries.geojson

Output: shared/src/commonMain/kotlin/io/github/nanunic9379/rideplan/route/CountryBorders.kt

What it does, per country of the rules table:
- keeps only the parts inside a Europe box (drops French Guiana, Svalbard far north is kept);
- simplifies every ring (Douglas-Peucker, TOLERANCE degrees, about 500 m);
- drops islands smaller than MIN_AREA square degrees, but always keeps the biggest part;
- writes each ring as an encoded polyline (Google algorithm) with PRECISION decimals.
Holes (San Marino and the Vatican inside Italy) are kept as rings: the app uses the even-odd rule.

Usage: python -I data/country_borders.py path/to/ne_10m_admin_0_countries.geojson
Standard library only.
"""
import json
import sys
from pathlib import Path

COUNTRIES = [
    "AD", "AL", "AT", "BA", "BE", "BG", "CH", "CZ", "DE", "DK", "EE", "ES", "FI", "FR", "GB",
    "GR", "HR", "HU", "IE", "IT", "LI", "LT", "LU", "LV", "MC", "MD", "ME", "MK", "MT", "NL",
    "NO", "PL", "PT", "RO", "RS", "SE", "SI", "SK", "SM", "XK",
]
EUROPE = (-25.0, 34.0, 45.0, 72.0)  # lon min, lat min, lon max, lat max
TOLERANCE = 0.005
MIN_AREA = 0.003
PRECISION = 3  # 0.001 degrees: about 110 m
OUT = Path(__file__).resolve().parent.parent / "shared/src/commonMain/kotlin/io/github/nanunic9379/rideplan/route/CountryBorders.kt"


def area(ring):
    return abs(sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]))) / 2


def simplify(points, tol):
    if len(points) < 3:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        a, b = stack.pop()
        (ax, ay), (bx, by) = points[a], points[b]
        dx, dy = bx - ax, by - ay
        norm = (dx * dx + dy * dy) ** 0.5
        best, index = -1.0, -1
        for i in range(a + 1, b):
            px, py = points[i]
            d = abs(dy * (px - ax) - dx * (py - ay)) / norm if norm else ((px - ax) ** 2 + (py - ay) ** 2) ** 0.5
            if d > best:
                best, index = d, i
        if best > tol:
            keep[index] = True
            stack += [(a, index), (index, b)]
    return [p for p, k in zip(points, keep) if k]


def encode(ring):
    factor = 10 ** PRECISION
    out, last = [], (0, 0)
    for lon, lat in ring:
        cur = (round(lat * factor), round(lon * factor))
        for v in (cur[0] - last[0], cur[1] - last[1]):
            v = ~(v << 1) if v < 0 else v << 1
            while v >= 0x20:
                out.append(chr((0x20 | (v & 0x1F)) + 63))
                v >>= 5
            out.append(chr(v + 63))
        last = cur
    return "".join(out)


def inside_europe(ring):
    xs = [p[0] for p in ring]
    ys = [p[1] for p in ring]
    return min(xs) >= EUROPE[0] and max(xs) <= EUROPE[2] and min(ys) >= EUROPE[1] and max(ys) <= EUROPE[3]


def main(src):
    data = json.load(open(src, encoding="utf-8"))
    by_code = {}
    for f in data["features"]:
        g = f["geometry"]
        by_code.setdefault(f["properties"]["ISO_A2_EH"], []).extend(
            g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]])
    lines = []
    total = 0
    for code in COUNTRIES:
        polys = [p for p in by_code[code] if inside_europe(p[0])]
        biggest = max(polys, key=lambda p: area(p[0]))
        rings = []
        for p in polys:
            if p is not biggest and area(p[0]) < MIN_AREA:
                continue
            for ring in p:
                r = simplify(ring[:-1] if ring[0] == ring[-1] else ring, TOLERANCE)
                if len(r) >= 3:
                    rings.append(encode(r))
        total += sum(len(r) for r in rings)
        body = ",\n".join(f'            """{r}"""' for r in rings)
        lines.append(f'        "{code}" to listOf(\n{body},\n        ),')
    OUT.write_text(
        "// Generated by data/country_borders.py from Natural Earth 1:10m Admin 0 - Countries v5.1.2\n"
        "// (public domain). Do not edit by hand: change the script and run it again.\n"
        "package io.github.nanunic9379.rideplan.route\n\n"
        "/** Coarse country outlines (#15): ISO code to rings as encoded polylines, "
        f"{PRECISION} decimals, about {int(TOLERANCE * 111000)} m simplification. */\n"
        "internal object CountryBorders {\n"
        f"    const val PRECISION = {PRECISION}\n\n"
        "    val rings: Map<String, List<String>> = mapOf(\n"
        + "\n".join(lines)
        + "\n    )\n}\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"{len(COUNTRIES)} countries, {total} characters")


if __name__ == "__main__":
    main(sys.argv[1])
